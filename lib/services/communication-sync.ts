/**
 * Called when a user leaves a team - removes from department channel
 */
export async function onUserLeftTeam(userId: string, teamId: string) {
  try {
    // Find department channel
    const departmentChannel = await prisma.chatChannel.findFirst({
      where: {
        type: 'DEPARTMENT',
        departmentId: teamId,
        isActive: true
      }
    })

    if (departmentChannel) {
      await prisma.chatMember.updateMany({
        where: {
          channelId: departmentChannel.id,
          userId
        },
        data: { leftAt: new Date() }
      })
    }

    return { success: true }
  } catch (error) {
    console.error('Error in onUserLeftTeam:', error)
    return { success: false, error: 'Failed to remove user from department channel' }
  }
}

/**
 * Called when a leave request is approved - creates notification
 */
export async function onLeaveApproved(leaveRequestId: string) {
  try {
    const leaveRequest = await prisma.leaveRequest.findUnique({
      where: { id: leaveRequestId },
      include: {
        employee: {
          include: { user: true }
        }
      }
    })

    if (!leaveRequest) return { success: false, error: 'Leave request not found' }

    // Create notification for the employee
    await prisma.notification.create({
      data: {
        userId: leaveRequest.employee.userId,
        type: 'SYSTEM',
        title: 'Leave Request Approved',
        content: `Your leave request from ${leaveRequest.startDate.toDateString()} to ${leaveRequest.endDate.toDateString()} has been approved.`,
        actionUrl: '/dashboard/leave'
      }
    })

    return { success: true }
  } catch (error) {
    console.error('Error in onLeaveApproved:', error)
    return { success: false, error: 'Failed to create leave approval notification' }
  }
}

/**
 * Called when a task is assigned - creates notification
 */
export async function onTaskAssigned(taskId: string, assigneeId: string) {
  try {
    const task = await prisma.task.findUnique({
      where: { id: taskId },
      include: {
        createdBy: {
          select: { name: true, firstName: true, lastName: true }
        }
      }
    })

    if (!task) return { success: false, error: 'Task not found' }

    const creatorName = task.createdBy?.name || 
                       `${task.createdBy?.firstName} ${task.createdBy?.lastName}`.trim() || 
                       'Someone'

    await prisma.notification.create({
      data: {
        userId: assigneeId,
        type: 'TASK_ASSIGNED',
        title: 'New Task Assigned',
        content: `${creatorName} assigned you a new task: ${task.title}`,
        actionUrl: `/dashboard/tasks?task=${taskId}`,
        data: JSON.stringify({
          taskId,
          taskTitle: task.title,
          assignedBy: task.createdById
        })
      }
    })

    return { success: true }
  } catch (error) {
    console.error('Error in onTaskAssigned:', error)
    return { success: false, error: 'Failed to create task assignment notification' }
  }
}

