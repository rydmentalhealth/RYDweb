import { prisma } from "@/lib/db"
import { 
  createNewMemberAnnouncement,
  createAchievementAnnouncement,
  createProjectUpdateAnnouncement
} from "./communication"

/**
 * Sync service to integrate communication with other modules
 */

/**
 * Called when a new user is approved - creates welcome announcement and adds to department channels
 */
export async function onUserApproved(userId: string) {
  try {
    // Create welcome announcement
    await createNewMemberAnnouncement(userId)

    // Get user's department
    const user = await prisma.user.findUnique({
      where: { id: userId },
      select: { department: true }
    })

    if (user?.department) {
      // Find department team
      const team = await prisma.team.findFirst({
        where: { name: user.department }
      })

      if (team) {
        // Add user to team
        await prisma.userTeam.upsert({
          where: {
            userId_teamId: {
              userId,
              teamId: team.id
            }
          },
          update: {},
          create: {
            userId,
            teamId: team.id,
            role: 'MEMBER'
          }
        })

        // Find department channel and add user
        const departmentChannel = await prisma.chatChannel.findFirst({
          where: {
            type: 'DEPARTMENT',
            departmentId: team.id,
            isActive: true
          }
        })

        if (departmentChannel) {
          await prisma.chatMember.upsert({
            where: {
              channelId_userId: {
                channelId: departmentChannel.id,
                userId
              }
            },
            update: { leftAt: null }, // Rejoin if previously left
            create: {
              channelId: departmentChannel.id,
              userId,
              role: 'MEMBER'
            }
          })
        }
      }
    }

    return { success: true }
  } catch (error) {
    console.error('Error in onUserApproved:', error)
    return { success: false, error: 'Failed to sync user approval' }
  }
}

