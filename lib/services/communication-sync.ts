/**
 * Called when a project status changes
 */
export async function onProjectStatusChange(projectId: string, oldStatus: string, newStatus: string) {
  try {
    let updateType: 'STARTED' | 'COMPLETED' | 'MILESTONE' | null = null

    if (oldStatus === 'PLANNING' && newStatus === 'ACTIVE') {
      updateType = 'STARTED'
    } else if (newStatus === 'COMPLETED') {
      updateType = 'COMPLETED'
    } else if (oldStatus !== newStatus) {
      updateType = 'MILESTONE'
    }

    if (updateType) {
      await createProjectUpdateAnnouncement(projectId, updateType)
    }

    return { success: true }
  } catch (error) {
    console.error('Error in onProjectStatusChange:', error)
    return { success: false, error: 'Failed to create project update' }
  }
}

/**
 * Called when a new team is created - creates department channel
 */
export async function onTeamCreated(teamId: string) {
  try {
    const team = await prisma.team.findUnique({
      where: { id: teamId },
      include: {
        members: {
          include: { user: true }
        }
      }
    })

    if (!team || team.members.length === 0) {
      return { success: false, error: 'Team not found or has no members' }
    }

    // Create department channel
    const channel = await prisma.chatChannel.create({
      data: {
        name: `${team.name} Team`,
        description: `Official channel for ${team.name} department`,
        type: 'DEPARTMENT',
        departmentId: team.id,
        isAutoGenerated: true,
        createdById: team.members[0].userId
      }
    })

    // Add all team members
    const memberData = team.members.map(member => ({
      channelId: channel.id,
      userId: member.userId,
      role: member.role === 'LEADER' ? 'ADMIN' as const : 'MEMBER' as const
    }))

    await prisma.chatMember.createMany({
      data: memberData
    })

    // Send welcome message
    await prisma.chatMessage.create({
      data: {
        channelId: channel.id,
        authorId: team.members[0].userId,
        content: `Welcome to the ${team.name} team channel! 🎉 This is your space for team discussions, updates, and collaboration.`,
        messageType: 'SYSTEM'
      }
    })

    return { success: true, channelId: channel.id }
  } catch (error) {
    console.error('Error in onTeamCreated:', error)
    return { success: false, error: 'Failed to create department channel' }
  }
}

